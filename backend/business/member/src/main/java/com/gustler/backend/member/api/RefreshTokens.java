package com.gustler.backend.member.api;

import java.util.UUID;

/**
 * 로그인을 이어 가게 해 주는 리프레시 토큰을 발급하고 갱신하고 폐기한다.
 *
 * <p>토큰은 한 번 로그인할 때마다 하나의 계통(family)을 이룬다. 계통에는 현재 세대가 하나 있고, 갱신하면 세대가 하나
 * 올라 같은 계통의 새 토큰이 나온다. 토큰은 서버 비밀로 서명한 값이라 (계통, 세대)가 같으면 항상 같은 토큰이다.
 * 만료는 현재 세대를 발급한 시점부터 30일이라 쓰는 동안은 계속 이어지지만, 처음 로그인한 뒤 180일을 넘지 않는다.
 */
public interface RefreshTokens {
    /** 새 로그인 계통을 시작한다. 로그인에 성공한 회원에게 발급한다. */
    IssuedRefreshToken issue(UUID publicId);

    /**
     * 토큰을 새 토큰으로 바꾼다.
     *
     * <p>한 세대 전 토큰이 10초 안에 다시 오면 상태를 바꾸지 않고 먼저 갱신한 요청이 받은 것과 같은 현재 토큰을 돌려준다.
     * 같은 사용자의 탭 두 개가 동시에 갱신해도 둘이 같은 토큰을 받게 하려는 것이다. 그 시간이 지났거나 두 세대 이상
     * 오래된 토큰이 오면 탈취로 보고 계통을 폐기한다. 서명이 맞지 않는 토큰은 모르는 토큰이다.
     */
    RefreshResult rotate(String token);

    /** 이 토큰이 속한 계통을 폐기한다. 세대와 상관없이 서명이 맞으면 폐기하고, 모르는 토큰이면 아무 일도 하지 않는다. */
    void revoke(String token);

    /**
     * 회원의 계통을 모두 폐기하고 폐기한 계통 수를 돌려준다. 회원이 없거나 남은 계통이 없으면 0 이다.
     *
     * <p>모든 기기에서 로그아웃할 때 쓴다. 리프레시 토큰만 폐기하므로 이미 발급된 액세스 토큰은 만료(최대 15분)까지 남는다.
     */
    int revokeAll(UUID publicId);

    /**
     * 만료된 계통을 한 묶음 지우고 지운 개수를 돌려준다.
     *
     * <p>지우는 대상은 만료된 계통뿐이다. 계통에는 현재 세대 하나만 남으므로 사용을 마친 토큰을 따로 두지 않는다.
     * 한 번에 지우는 개수에 상한이 있어, 돌려준 개수가 상한과 같으면 더 남아 있을 수 있으니 다시 부른다.
     */
    int purgeObsolete();

    /** {@link #purgeObsolete()} 가 한 번에 지우는 최대 개수. */
    int PURGE_BATCH_SIZE = 1_000;
}
