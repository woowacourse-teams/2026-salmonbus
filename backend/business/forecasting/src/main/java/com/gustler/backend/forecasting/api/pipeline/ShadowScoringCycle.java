package com.gustler.backend.forecasting.api.pipeline;

/**
 * 그림자 채점의 주기 작업과 종료 절차다. 실행하는 앱(worker)이 기동 직후와 몇 초마다, 그리고 내려가기 전에 부른다.
 *
 * <p>모든 메서드는 예외를 던지지 않는다. 실패는 로그와 지표로 남긴다.
 */
public interface ShadowScoringCycle {
    /**
     * 최근 예보가 있는 노선을 모두 한 번 되감는 일을 채점 줄에 넣는다. 기동이 끝난 뒤 한 번 부른다.
     *
     * @return 줄에 넣었으면 참
     */
    boolean start();

    /**
     * 사건을 버린 노선을 되감고 오래 배치가 없는 노선의 마감을 닫는 일을 채점 줄에 넣는다.
     *
     * @return 줄에 넣었으면 참. 줄이 가득 찼으면 거짓이고 이번 회차는 건너뛴다
     */
    boolean tick();

    /**
     * 모아 둔 정답·미해결 줄을 쓴다. 실패하면 줄을 남겨 두고 다음 회차에 다시 쓴다.
     *
     * @return 새로 넣은 줄 수. 실패했으면 0
     */
    int flush();

    /**
     * 사건과 주기 호출을 더 받지 않는다. 내려가기 전에 부른다. 어느 스레드에서 여러 번 불러도 된다.
     *
     * <p>부른 뒤에 온 사건은 채점 줄에 넣지 않고 버린 사건으로도 세지 않는다. 저장된 사건이므로 다음 기동의 되감기가 읽는다.
     * {@link #start()}와 {@link #tick()}은 거짓을 돌려준다. 이미 채점 줄에 들어간 일은 그대로 실행되므로 줄을 비우는 것은
     * 부르는 쪽이 한다. {@link #flush()}와 {@link #flushRemaining()}은 계속 쓸 수 있다.
     */
    void stopAccepting();

    /**
     * 모아 둔 정답·미해결 줄을 지금 쓴다. 내려가기 전의 마지막 쓰기다. 채점 줄을 비운 뒤에 불러야 그때까지 나온 결과가 모두
     * 들어간다. 어느 스레드에서 여러 번 불러도 되며, 쓰기가 끝날 때까지 막는다.
     *
     * @return 쓰지 못하고 남은 줄 수. 0이면 남은 것이 없다. 0보다 크면 쓰기가 실패한 것이고 다시 불러도 된다
     */
    int flushRemaining();
}
